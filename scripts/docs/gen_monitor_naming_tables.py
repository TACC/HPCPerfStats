#!/usr/bin/env python3
"""
Generate docs/reference/monitor-naming-tables.md from the packaged rename map.

The rename map ``hpcperfstats/dbload/lib/monitor_naming/
monitor_variable_rename_map.yaml`` is runtime data: ``load_map.py`` loads it
and ``legacy.py`` / ``resolve.py`` use it to read archives and ``host_data``
rows that carry legacy names. This script renders every section of the map as
tables.

Run from the checkout root::

  ../.venv/bin/python3 scripts/docs/gen_monitor_naming_tables.py
  ../.venv/bin/python3 scripts/docs/gen_monitor_naming_tables.py --check

The ``monitor-naming-tables`` pre-commit hook runs ``--fix`` when a commit
touches this script, the page, the rename map or ``load_map.py``. A stale
page is rewritten and the hook fails. Run this script in the checkout, then
commit the page with the other paths: ``git isolated-commit`` runs hooks in a
slot worktree, so the rewrite never reaches the checkout, and a named page
that still matches ``HEAD`` is not part of the commit.
``hpcperfstats/tests/test_doc_generators_fresh.py`` runs ``--check``
for commits that skip hooks, and pins the hook's ``files:`` pattern to these
inputs.

Attributes:
  REPO (Path): Checkout root.
  OUT (Path): Generated page.
  SCRIPT (str): This script, relative to ``REPO`` (cited in the page).
  MAP_REL (str): Rename map path, relative to ``REPO``.
  MAP_SECTIONS (tuple[tuple[str, str, str, str], ...]): Flat map sections
    rendered as two-column tables: (YAML key, heading, left column, intro).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from hpcperfstats.dbload.lib.monitor_naming.load_map import (  # noqa: E402
  load_monitor_rename_map,
)

OUT = REPO / "docs" / "reference" / "monitor-naming-tables.md"
SCRIPT = "scripts/docs/gen_monitor_naming_tables.py"
MAP_REL = (
  "hpcperfstats/dbload/lib/monitor_naming/monitor_variable_rename_map.yaml"
)
MAP_SECTIONS = (
  (
    "types",
    "Type renames",
    "Legacy type",
    "Each legacy `st_name` and the canonical type ingest and analysis read"
    " it as (`resolve.canonical_type_name`, `resolve.type_probe_names`).",
  ),
  (
    "events",
    "Event renames",
    "Legacy key",
    "Global key renames, applied on every type (`resolve.events_probe_names`).",
  ),
  (
    "host_mem_aliases",
    "Host memory aliases",
    "Kernel field",
    "`/proc/meminfo` field names and the `host_mem` keys the monitor emits"
    " for them.",
  ),
  (
    "host_proc_aliases",
    "Host process aliases",
    "Kernel field",
    "`/proc/<PID>/status` field names and the `host_proc` keys the monitor"
    " emits for them.",
  ),
)


def _pair_table(left: str, mapping: dict) -> list[str]:
  """
  Render a mapping as a two-column table in YAML order.

  Args:
    left (str): Header of the first column.
    mapping (dict): Old name -> new name.

  Returns:
    list[str]: Markdown table lines.

  Examples:
    >>> _pair_table("Legacy key", {"APERF": "aperf"})[2]
    '| `APERF` | `aperf` |'
  """
  rows = [f"| {left} | Canonical name |", "| --- | --- |"]
  rows += [f"| `{old}` | `{new}` |" for old, new in mapping.items()]
  return rows


def _code_list(names: list) -> str:
  """
  Join names as code spans.

  Args:
    names (list): Symbols to list.

  Returns:
    str: Comma-separated code spans.

  Examples:
    >>> _code_list(["CTL0", "CTR0"])
    '`CTL0`, `CTR0`'
  """
  return ", ".join(f"`{n}`" for n in names)


def render(data: dict) -> str:
  """
  Build the page text from the loaded rename map.

  Args:
    data (dict): ``load_monitor_rename_map()`` output.

  Returns:
    str: Markdown for ``OUT``, ending in a newline.

  Examples:
    >>> render({"types": {"cpu": "host_cpu"}}).splitlines()[0]
    '# Monitor naming tables'
  """
  lines = [
    "# Monitor naming tables",
    "",
    f"Generated by `{SCRIPT}`; do not edit.",
    "",
    "This page lists every legacy-to-canonical name in the monitor rename"
    f" map `{MAP_REL}`, for developers who read older archives or change"
    " the map.",
    "The monitor emits only canonical names.",
    "Ingest and analysis still read legacy names through this map:"
    " `load_map.py` loads it, `legacy.py` builds the alias tables, and"
    " `resolve.py` probes canonical names first, then legacy ones.",
    "The naming rules are in"
    " [Monitor naming scheme](../explanation/monitor-naming-scheme.md).",
  ]
  for key, heading, left, intro in MAP_SECTIONS:
    lines += ["", f"## {heading}", "", intro, ""]
    lines += _pair_table(left, data.get(key) or {})
  lines += [
    "",
    "## Type-scoped event renames",
    "",
    "Renames that apply on one type only, because the legacy key collides"
    " with a key of another type (`load_map.type_event_renames`).",
  ]
  for typ, mapping in (data.get("type_events") or {}).items():
    lines += ["", f"### {typ}", ""]
    lines += _pair_table("Legacy key", mapping)
  lines += [
    "",
    "## File event overrides",
    "",
    "Per-source key overrides; no file in `monitor/src` has these names and"
    " no consumer code reads this section.",
    "",
    "| Source file | Key | Emitted as |",
    "| --- | --- | --- |",
  ]
  for src, mapping in (data.get("file_event_overrides") or {}).items():
    lines += [f"| `{src}` | `{k}` | `{v}` |" for k, v in mapping.items()]
  lines += [
    "",
    "## Removed legacy symbols",
    "",
    "The monitor never emits these symbols.",
    "A schema that carries one is decoded as a legacy `CTL*` / `CTR*`"
    " schema (`legacy.REMOVED_LEGACY_SYMBOLS`,"
    " `resolve.schema_needs_legacy_hardware_decode`).",
    "",
    _code_list(data.get("removed_legacy") or []),
    "",
    "## Removed legacy events",
    "",
    "Retired keys of a live type.",
    "They stay out of the flat list above, so a schema that carries them"
    " keeps the current decode.",
    "",
    "| Type | Retired keys |",
    "| --- | --- |",
  ]
  for typ, keys in (data.get("removed_legacy_events") or {}).items():
    lines.append(f"| `{typ}` | {_code_list(keys)} |")
  return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
  """
  Write the page, or check it with ``--check`` or refresh it with ``--fix``.

  ``--fix`` is the pre-commit hook mode: it rewrites a stale page and fails
  with the command to run and the path to commit, and passes without writing
  when the page is current.

  Args:
    argv (list[str] | None): Command-line arguments (default ``sys.argv``).

  Returns:
    int: 0 on success or when up to date, 1 when ``--check`` finds drift
    or ``--fix`` rewrote the page.

  Examples:
    >>> main(["--check"])  # doctest: +SKIP
    0
  """
  ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
  mode = ap.add_mutually_exclusive_group()
  mode.add_argument(
    "--check", action="store_true", help="fail if the page is stale"
  )
  mode.add_argument(
    "--fix",
    action="store_true",
    help="rewrite a stale page and fail (pre-commit hook mode)",
  )
  args = ap.parse_args(argv)
  text = render(load_monitor_rename_map())
  rel = OUT.relative_to(REPO)
  current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
  if (args.check or args.fix) and current == text:
    print(f"{rel} up to date")
    return 0
  if args.check:
    print(f"{rel} is stale; run {SCRIPT}")
    return 1
  OUT.write_text(text, encoding="utf-8")
  if args.fix:
    print(
      f"{rel} was stale: run ../.venv/bin/python3 {SCRIPT} in the"
      f" checkout, then commit {rel} with the other paths"
    )
    return 1
  print(f"Wrote {rel}")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
