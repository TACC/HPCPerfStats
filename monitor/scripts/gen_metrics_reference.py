#!/usr/bin/env python3
"""Generate docs/METRICS_REFERENCE.md: every stats type and key the monitor can emit.

Keys, flags, units, widths, tiers and build conditions come from the C sources
(``scripts/lib/keys_catalog.py``); the human descriptions come from
``docs/metric_descriptions.tsv`` (``type<TAB>key<TAB>description``, plus one ``@type`` and one
``@dev`` row per type). A key with no TSV row falls back to its KEYS macro description.

Usage:
    scripts/gen_metrics_reference.py           # rewrite docs/METRICS_REFERENCE.md
    scripts/gen_metrics_reference.py --check   # exit 1 when the doc or the TSV is stale

``--check`` (run by ``make check`` through ``tests/test_metrics_reference.sh``) fails when:
a type or key has no description, the TSV describes a type or key the sources no longer
emit, a description has non-ASCII text, or the committed doc differs from the generated one.
"""

import argparse
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from lib.keys_catalog import load_catalog  # noqa: E402

TSV = ROOT / "docs" / "metric_descriptions.tsv"
DOC = ROOT / "docs" / "METRICS_REFERENCE.md"
TYPE_ROWS = ("@type", "@dev")

INTRO = """# Monitor metrics reference

<!-- GENERATED by scripts/gen_metrics_reference.py from src/ KEYS macros and
docs/metric_descriptions.tsv. Do not edit by hand: edit the TSV (or the C KEYS) and re-run
the script. `make check` fails when this file is stale. -->

Every stats type the monitor can emit and every key of each type, in emit order. For the
file format itself (headers, schema lines, rows, sentinels, tiers) and the Python reader, see
[RAW_DATA_FORMAT.md](RAW_DATA_FORMAT.md).

A given node emits only the types its build and hardware support; its own `!` schema lines
are the authority for what a file contains. Column legend:

| Column | Meaning |
|--------|---------|
| Kind | **counter** (`E` flag): running total, use the difference between two samples (divide by the elapsed seconds for a rate). **gauge**: an instantaneous level, read as is. |
| Unit | Unit after applying the multiplier: `x512 B` means value x 512 = bytes. `-` means a plain count or a dimensionless number. |
| W | Counter width in bits: the counter wraps to 0 after `2^W - 1` (64 unless shown). |
| Tier | **slow** keys are carried only by `@full` rows (every `sample_freq_slow`, default 600 s) when two-tier collection is on; **fast** keys are in every row. |
| Build | Preprocessor condition the key is declared under; empty when every build declares it. Keys a build or CPU cannot read are still emitted, as a sentinel (`-2` NOT_PRESENT, `-10` NOT_BUILT). |
"""


def load_descriptions(path):
    """Return {(type, key): description}; raise ValueError on malformed lines."""
    out = {}
    lines = path.read_text(encoding="utf-8").splitlines()
    for no, line in enumerate(lines[1:], 2):
        if not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise ValueError("%s:%d: expected 3 tab-separated fields" % (path.name, no))
        typ, key, desc = (p.strip() for p in parts)
        if (typ, key) in out:
            raise ValueError("%s:%d: duplicate %s %s" % (path.name, no, typ, key))
        out[(typ, key)] = desc
    return out


def _cell(text):
    return text.replace("|", "\\|")


def _unit(opts):
    for opt in opts.split(","):
        name, _, arg = opt.strip().partition("=")
        if name.upper() == "U" and arg:
            digits = len(arg) - len(arg.lstrip("0123456789"))
            if 0 < digits < len(arg):
                return "x%s %s" % (arg[:digits], arg[digits:])
            return arg
    return "-"


def _width(opts):
    for opt in opts.split(","):
        name, _, arg = opt.strip().partition("=")
        if name.upper() == "W" and arg:
            return arg
    return "64"


def _is_event(opts):
    return any(o.strip().upper() == "E" for o in opts.split(","))


def problems(catalog, desc):
    """Return a list of human-readable consistency problems."""
    out = []
    for typ, t in catalog.items():
        for key in TYPE_ROWS:
            if not desc.get((typ, key)):
                out.append("missing description: %s %s" % (typ, key))
        for key, k in t["keys"].items():
            if not desc.get((typ, key)) and not k["description"]:
                out.append("missing description: %s %s" % (typ, key))
    for typ, key in desc:
        if typ not in catalog:
            out.append("TSV describes a type the sources do not emit: %s" % typ)
        elif key not in TYPE_ROWS and key not in catalog[typ]["keys"]:
            out.append("TSV describes a key the sources do not emit: %s %s" % (typ, key))
    for (typ, key), text in desc.items():
        if any(ord(ch) > 126 for ch in text):
            out.append("non-ASCII description: %s %s" % (typ, key))
    return out


def render(catalog, desc):
    lines = [INTRO, "## Types", ""]
    lines.append("| Type | Keys | Source |")
    lines.append("|------|------|--------|")
    for typ, t in catalog.items():
        lines.append(
            "| [`%s`](#%s) | %d | %s |"
            % (typ, typ, len(t["keys"]), ", ".join("`src/%s`" % s for s in t["sources"]))
        )
    lines.append("")
    for typ, t in catalog.items():
        lines.append("## %s" % typ)
        lines.append("")
        lines.append(desc.get((typ, "@type"), ""))
        lines.append("")
        lines.append("**Device field:** %s" % desc.get((typ, "@dev"), ""))
        lines.append("")
        lines.append("Source: %s." % ", ".join("`src/%s`" % s for s in t["sources"]))
        lines.append("")
        lines.append("| Key | Kind | Unit | W | Tier | Build | Description |")
        lines.append("|-----|------|------|---|------|-------|-------------|")
        for key, k in t["keys"].items():
            text = desc.get((typ, key)) or k["description"]
            lines.append(
                "| `%s` | %s | %s | %s | %s | %s | %s |"
                % (
                    key,
                    "counter" if _is_event(k["options"]) else "gauge",
                    _cell(_unit(k["options"])),
                    _width(k["options"]),
                    "slow" if k["slow"] else "fast",
                    _cell("; ".join("`%s`" % c for c in k["conditions"])),
                    _cell(text),
                )
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    args = ap.parse_args(argv)
    catalog = load_catalog(ROOT / "src")
    desc = load_descriptions(TSV)
    errs = problems(catalog, desc)
    text = render(catalog, desc)
    if args.check:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current != text:
            diff = difflib.unified_diff(
                current.splitlines(), text.splitlines(), "committed", "generated", lineterm="", n=0
            )
            errs.append("docs/METRICS_REFERENCE.md is stale; first differences:")
            errs.extend("  " + d for d in list(diff)[:20])
        for e in errs:
            print("gen_metrics_reference: " + e, file=sys.stderr)
        if errs:
            print("gen_metrics_reference: fix docs/metric_descriptions.tsv and run "
                  "scripts/gen_metrics_reference.py", file=sys.stderr)
            return 1
        print("gen_metrics_reference: %d types, %d keys, doc up to date"
              % (len(catalog), sum(len(t["keys"]) for t in catalog.values())))
        return 0
    for e in errs:
        print("gen_metrics_reference: " + e, file=sys.stderr)
    DOC.write_text(text, encoding="utf-8")
    print("wrote %s" % DOC.relative_to(ROOT))
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
