#!/usr/bin/env python3
"""
Generate the measurement summary block in README.md from profiles.csv.

``docs/measurements/overhead_profile/profiles.csv`` is the cross-node table
of the monitor overhead campaign (one row per node type, written by
``monitor/measurement/bin/aggregate_profiles.py``). This script renders a
short summary of it between the ``BEGIN`` and ``END`` markers in
``README.md`` and leaves the rest of the README alone.

Run from the checkout root::

  ../.venv/bin/python3 scripts/docs/gen_readme_measurement_summary.py
  ../.venv/bin/python3 scripts/docs/gen_readme_measurement_summary.py --check

The ``readme-measurement-summary`` pre-commit hook runs ``--fix`` when a
commit touches this script, ``README.md`` or the CSV. A stale block is
rewritten and the hook fails. Run this script in the checkout, then commit
``README.md`` with the other paths: ``git isolated-commit`` runs hooks in a
slot worktree, so the rewrite never reaches the checkout.
``hpcperfstats/tests/test_doc_generators_fresh.py`` runs ``--check`` for
commits that skip hooks, and pins the hook's ``files:`` pattern to these
inputs.

Attributes:
  REPO (Path): Checkout root.
  README (Path): The page that holds the generated block.
  SCRIPT (str): This script, relative to ``REPO`` (cited in the marker).
  CSV_REL (str): Cross-node profile table, relative to ``REPO``.
  TABLE_REL (str): Markdown copy of that table, relative to ``REPO``.
  CAMPAIGN_REL (str): Campaign record, relative to ``REPO``; its file name
    carries the monitor version (``v31`` is 3.1) and ends in the campaign
    date.
  BEGIN (str): Opening marker line of the generated block.
  END (str): Closing marker line of the generated block.
"""

from __future__ import annotations

import argparse
import csv
import re
import statistics
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
README = REPO / "README.md"
SCRIPT = "scripts/docs/gen_readme_measurement_summary.py"
CSV_REL = "docs/measurements/overhead_profile/profiles.csv"
TABLE_REL = "docs/measurements/overhead_profile/profiles.md"
CAMPAIGN_REL = "docs/measurements/monitor_overhead_campaign_v31_2026-11-26.md"
BEGIN = f"<!-- BEGIN generated by {SCRIPT}; do not edit -->"
END = "<!-- END generated measurement summary -->"


def _num(value: float) -> str:
  """
  Format a number to 3 significant digits in positional notation.

  Args:
    value (float): Number to format.

  Returns:
    str: The rounded value with no exponent and no trailing zeros.

  Examples:
    >>> _num(724.1209)
    '724'
    >>> _num(0.000312)
    '0.000312'
  """
  text = f"{float(f'{value:.3g}'):f}"
  return text.rstrip("0").rstrip(".") if "." in text else text


def render(rows: list[dict[str, str]]) -> str:
  """
  Render the summary block, markers included, from the CSV rows.

  A blank line separates each marker from the prose, the form mdformat
  keeps, so the lint hooks and this generator agree on the block.

  Args:
    rows (list[dict[str, str]]): ``profiles.csv`` rows keyed by header.

  Returns:
    str: The block text from ``BEGIN`` through ``END``, newline-terminated.

  Raises:
    ValueError: When the CSV has no rows or the campaign record name has
      no version and date.

  Examples:
    >>> row = {
    ...   "host": "n1",
    ...   "arch": "x86_64",
    ...   "cpu_model": "C",
    ...   "daemon_cpu_core_s_per_h": "2",
    ...   "daemon_cpu_pct_node": "0.1",
    ... }
    >>> "1 node type (1 x86_64)" in render([row])
    True
  """
  if not rows:
    raise ValueError(f"{CSV_REL} has no rows")
  name = re.search(r"_v(\d)(\d+)_(\d{4}-\d{2}-\d{2})\.md$", CAMPAIGN_REL)
  if name is None:
    raise ValueError(f"{CAMPAIGN_REL} name has no version and date")
  version, date = f"{name.group(1)}.{name.group(2)}", name.group(3)
  cpu = [float(r["daemon_cpu_core_s_per_h"]) for r in rows]
  pct = [float(r["daemon_cpu_pct_node"]) for r in rows]
  top = max(rows, key=lambda r: float(r["daemon_cpu_core_s_per_h"]))
  arches = ", ".join(
    f"{n} {arch}"
    for arch, n in sorted(Counter(r["arch"] for r in rows).items())
  )
  kinds = "node type" if len(rows) == 1 else "node types"
  lines = [
    BEGIN,
    "",
    f"The monitor overhead campaign of {date} profiled"
    f" `hpcperfstatsd` {version} on {len(rows)} {kinds} ({arches}).",
    f"Daemon CPU had a median of {_num(statistics.median(cpu))} core-s/h"
    f" and ranged from {_num(min(cpu))} to {_num(max(cpu))} core-s/h,"
    f" or {_num(min(pct))}% to {_num(max(pct))}% of node capacity.",
    f"The highest was on {top['host']} ({top['cpu_model']}).",
    f"The [campaign record]({CAMPAIGN_REL}) has the per-node detail, and"
    f" [Overhead profiles]({TABLE_REL}) has every metric.",
    "",
    END,
  ]
  return "\n".join(lines) + "\n"


def splice(readme: str, block: str) -> str:
  """
  Replace the marked block in the README text.

  Args:
    readme (str): Current README text.
    block (str): New block from ``render``, markers included.

  Returns:
    str: README text with the block replaced.

  Raises:
    ValueError: When the README lacks exactly one ``BEGIN`` / ``END`` pair.

  Examples:
    >>> old = "\\n".join(["a", BEGIN, "old", END, "b", ""])
    >>> splice(old, "\\n".join([BEGIN, "new", END, ""])).split("\\n")[2]
    'new'
  """
  head, sep, rest = readme.partition(BEGIN + "\n")
  _, sep2, tail = rest.partition(END + "\n")
  if not sep or not sep2 or BEGIN in tail or BEGIN in head:
    raise ValueError(f"{README.name} needs one {BEGIN!r} ... {END!r} block")
  return head + block + tail


def main(argv: list[str] | None = None) -> int:
  """
  Write the block, or check it with ``--check`` or refresh it with ``--fix``.

  ``--fix`` is the pre-commit hook mode: it rewrites a stale block and fails
  with the command to run and the path to commit, and passes without writing
  when the block is current.

  Args:
    argv (list[str] | None): Command-line arguments (default ``sys.argv``).

  Returns:
    int: 0 on success or when up to date, 1 when ``--check`` finds drift
    or ``--fix`` rewrote the block.

  Examples:
    >>> main(["--check"])  # doctest: +SKIP
    0
  """
  ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
  mode = ap.add_mutually_exclusive_group()
  mode.add_argument(
    "--check", action="store_true", help="fail if the block is stale"
  )
  mode.add_argument(
    "--fix",
    action="store_true",
    help="rewrite a stale block and fail (pre-commit hook mode)",
  )
  args = ap.parse_args(argv)
  with (REPO / CSV_REL).open(encoding="utf-8", newline="") as fh:
    rows = list(csv.DictReader(fh))
  current = README.read_text(encoding="utf-8")
  text = splice(current, render(rows))
  if (args.check or args.fix) and current == text:
    print(f"{README.name} measurement summary up to date")
    return 0
  if args.check:
    print(f"{README.name} measurement summary is stale; run {SCRIPT}")
    return 1
  README.write_text(text, encoding="utf-8")
  if args.fix:
    print(
      f"{README.name} measurement summary was stale: run ../.venv/bin/python3"
      f" {SCRIPT} in the checkout, then commit {README.name}"
    )
    return 1
  print(f"Wrote {README.name} measurement summary")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
