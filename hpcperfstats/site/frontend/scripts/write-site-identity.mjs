import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { resolveGitCommit } from "./site-git-commit.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, "..");
const gitCheckoutRoot = path.resolve(frontendRoot, "../../..");
const outPath = path.resolve(frontendRoot, "src/config/site-identity.ts");

const INI_CANDIDATES = [
  path.join(gitCheckoutRoot, "hpcperfstats.ini"),
  path.join(gitCheckoutRoot, "hpcperfstats.ini.example"),
];

function parseDefaultSection(iniText) {
  const lines = iniText.split(/\r?\n/);
  const values = {};
  let inDefault = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || line.startsWith(";")) continue;
    const sectionMatch = line.match(/^\[([^\]]+)\]$/);
    if (sectionMatch) {
      inDefault = sectionMatch[1].toLowerCase() === "default";
      continue;
    }
    if (!inDefault) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    const value = line.slice(eq + 1).trim();
    values[key] = value;
  }
  return values;
}

function interpolateHostNameExt(hostNameExt, machine) {
  if (!hostNameExt) return "";
  return hostNameExt.replace(/%\(machine\)s/g, machine ?? "");
}

function resolveSiteIdentity() {
  let iniPath = null;
  for (const candidate of INI_CANDIDATES) {
    if (fs.existsSync(candidate)) {
      iniPath = candidate;
      break;
    }
  }
  if (!iniPath) {
    console.warn(
      "write-site-identity: no hpcperfstats.ini or .example found; SITE_MACHINE_* empty",
    );
    return { shortName: "", machineName: "" };
  }
  const defaults = parseDefaultSection(fs.readFileSync(iniPath, "utf8"));
  const machine = (defaults.machine ?? "").trim();
  const hostNameExt = defaults.host_name_ext ?? "";
  const machineName = interpolateHostNameExt(hostNameExt, machine).trim();
  if (!machineName) {
    console.warn(`write-site-identity: host_name_ext unresolved in ${path.basename(iniPath)}`);
  } else {
    console.log(`write-site-identity: SITE_MACHINE_NAME from ${path.basename(iniPath)}`);
  }
  if (machine) {
    console.log(`write-site-identity: SITE_MACHINE_SHORT_NAME=${machine}`);
  }
  return { shortName: machine, machineName };
}

function escapeTsString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const { shortName, machineName } = resolveSiteIdentity();
const gitCommit = resolveGitCommit({ gitCheckoutRoot });
if (gitCommit) {
  console.log(`write-site-identity: SITE_GIT_COMMIT=${gitCommit.slice(0, 7)}…`);
} else {
  console.warn(
    `write-site-identity: SITE_GIT_COMMIT unset (staff commit link hidden); ` +
      `checked env HPCPERFSTATS_GIT_COMMIT and .git under ${gitCheckoutRoot}`,
  );
}

const body = `/** Generated by scripts/write-site-identity.mjs — do not edit by hand. */
export const SITE_MACHINE_SHORT_NAME = "${escapeTsString(shortName)}";
export const SITE_MACHINE_NAME = "${escapeTsString(machineName)}";
export const SITE_GIT_COMMIT = "${escapeTsString(gitCommit)}";
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, body, "utf8");
console.log(`write-site-identity: wrote ${outPath}`);
