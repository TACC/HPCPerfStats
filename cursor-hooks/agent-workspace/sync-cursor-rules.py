#!/usr/bin/env python3
"""Generate Claude Code rule stubs from the Cursor rules (.cursor/rules/*.mdc).

The .mdc files stay the single source of truth. This script only derives:

  .claude/cursor-always-on.md        @-imports of every ``alwaysApply: true`` rule
  .claude/cursor-agent-requested.md  index of rules with no globs / not always-on
  .claude/rules/cursor-<name>.md     path-scoped stub per rule that has ``globs:``

Dual workspace (``.cursor/workspace-profile`` first word ``dual``): also derives monitor stubs
from ``HPCPerfStats/monitor/cursor-rules``, scoped to ``HPCPerfStats/monitor/**``:

  .claude/rules/cursor-mon-<name>.md   path-scoped stub per monitor rule with globs
  .claude/rules/cursor-mon-always-on.md  monitor always-on rules (Read-gated by the hooks)
  + a monitor section in cursor-agent-requested.md

Monitor always-on rules are NOT added to cursor-always-on.md: they forbid container edits
(monitor-workspace-contract.mdc), so they must load only for monitor work.

Stubs carry no rule content, only "Read the .mdc before editing" plus a ``paths:``
filter, so editing a rule needs no re-sync; adding/removing a rule or changing its
frontmatter does. Runs from the SessionStart hook; safe to run any time.

Usage: sync-cursor-rules.py [--check]   (--check exits 1 if anything would change)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLAUDE = ROOT / ".claude"
RULES_SRC = ROOT / ".cursor" / "rules"
MONITOR_RULES_SRC = ROOT / "HPCPerfStats" / "monitor" / "cursor-rules"
PROFILE_MARKER = ROOT / ".cursor" / "workspace-profile"
STUB_DIR = CLAUDE / "rules"
STUB_PREFIX = "cursor-"
MONITOR_STUB_PREFIX = "cursor-mon-"
MONITOR_SCOPE = "HPCPerfStats/monitor/**"
HEADER = (
  "<!-- GENERATED by .claude/scripts/sync-cursor-rules.py from .cursor/rules"
  " (and HPCPerfStats/monitor/cursor-rules in a dual workspace); do not edit -->\n"
)


def dual_workspace() -> bool:
  try:
    words = PROFILE_MARKER.read_text(encoding="utf-8").split()
  except OSError:
    return False
  return bool(words) and words[0].lower() == "dual"


def parse_frontmatter(text: str) -> dict:
  """Return the ``key: value`` pairs of a leading ``---`` block ({} if absent).

  YAML list values (``key:`` followed by ``  - item`` lines) are joined with commas, so
  list-form ``globs:`` reads the same as the comma form.
  """
  lines = text.splitlines()
  if not lines or lines[0].strip() != "---":
    return {}
  fm = {}
  key = None
  for line in lines[1:]:
    if line.strip() == "---":
      break
    m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
    if m:
      key = m.group(1)
      fm[key] = m.group(2).strip().strip("\"'")
      continue
    item = re.match(r"^\s+-\s+(.*)$", line)
    if item and key:
      val = item.group(1).strip().strip("\"'")
      fm[key] = f"{fm[key]},{val}" if fm[key] else val
  return fm


def claude_globs(raw: str) -> list:
  """Cursor globs (comma list, rooted at the git checkout) -> Claude ``paths`` globs."""
  out = []
  depth = 0
  cur = ""
  for ch in raw:  # split on commas outside {a,b} braces
    if ch == "{":
      depth += 1
    elif ch == "}":
      depth -= 1
    if ch == "," and depth == 0:
      out.append(cur)
      cur = ""
    else:
      cur += ch
  out.append(cur)
  globs = []
  for g in (x.strip() for x in out):
    if not g:
      continue
    if g.startswith("HPCPerfStats/"):
      g = g[len("HPCPerfStats/"):]
    if not g.startswith("**/"):
      g = "**/" + g
    if g not in globs:
      globs.append(g)
  return globs


def one_line(s: str) -> str:
  return " ".join(s.split())


def router_globs(entries_attr: str) -> dict:
  """rule filename (lower) -> Claude globs, from one Cursor hook router entry list."""
  sys.path.insert(0, str(ROOT / "HPCPerfStats" / "cursor-hooks"))
  try:
    import hook_task_router as router
  except Exception as exc:  # router unavailable: fall back to frontmatter globs only
    print(f"warning: router not importable ({exc})", file=sys.stderr)
    return {}
  out = {}
  for entry in getattr(router, entries_attr, []):
    pats = list(entry["patterns"]) + list(entry.get("exact_paths") or [])
    if entry["id"] == "readme_install":
      pats += ["README.md", "HPCPerfStats/README.md"]
    for rule in entry["rules"]:
      bucket = out.setdefault(rule.lower(), [])
      for g in claude_globs(",".join(pats)):
        if g.endswith("/*"):
          g += "*"
        if g not in bucket:
          bucket.append(g)
  return out


def monitor_only(globs: list) -> list:
  """Keep only globs that can match under HPCPerfStats/monitor/ (monitor rules never apply
  to container paths in a dual workspace). Empty when none do."""
  return [g for g in globs if g.startswith("**/monitor/")]


def scan(src: Path, entries_attr: str, monitor: bool) -> tuple:
  """(always-on names, [(name, desc)] requested, {stub path: content}) for one rule tree."""
  from_router = router_globs(entries_attr)
  prefix = MONITOR_STUB_PREFIX if monitor else STUB_PREFIX
  where = "HPCPerfStats/monitor/cursor-rules" if monitor else ".cursor/rules"
  always, requested, stubs = [], [], {}
  for mdc in sorted(src.glob("*.mdc")):
    name = mdc.stem
    fm = parse_frontmatter(mdc.read_text(encoding="utf-8", errors="replace"))
    desc = one_line(fm.get("description", "")) or name
    globs = claude_globs(fm.get("globs", ""))
    for g in from_router.get(mdc.name.lower(), []):
      if g not in globs:
        globs.append(g)
    if monitor:
      globs = monitor_only(globs)
    if fm.get("alwaysApply", "").lower() == "true":
      always.append(name)
    elif globs:
      scope = (
        " This is the monitor copy: it governs edits under `HPCPerfStats/monitor/` in this dual "
        "workspace, even when `.cursor/rules/` has a file of the same name."
        if monitor
        else ""
      )
      body = (
        f"{HEADER}\nCursor rule `{name}` (mandatory when triggered): {desc}\n\n"
        f"Before editing a file matching this rule's paths, Read "
        f"`{where}/{name}.mdc` in full and follow it. The Cursor hook router triggers it for "
        f"these paths, and the PreToolUse hook denies edits until it was Read this turn.{scope}\n"
      )
      front = "---\npaths:\n" + "".join(f"  - {json.dumps(g)}\n" for g in globs) + "---\n"
      stubs[STUB_DIR / f"{prefix}{name}.md"] = front + body
    else:
      requested.append((name, desc))
  return always, requested, stubs


def build() -> dict:
  """Map output path -> content for every generated file."""
  if not RULES_SRC.is_dir():
    sys.exit(f"missing {RULES_SRC}")
  always, requested, stubs = scan(RULES_SRC, "HPCPERFSTATS_ROUTER_ENTRIES", monitor=False)
  files = dict(stubs)
  files[CLAUDE / "cursor-always-on.md"] = (
    HEADER
    + "\n# Cursor rules: always on (mandatory)\n\n"
    + "".join(f"@.cursor/rules/{n}.mdc\n" for n in always).replace("@.cursor", "@../.cursor")
  )
  requested_md = (
    HEADER
    + "\n# Cursor rules: apply when relevant\n\n"
    + "These have no file globs. Read the `.mdc` when its description matches the task;\n"
    + "once triggered they are mandatory, not optional. Files live in `.cursor/rules/`.\n\n"
    + "".join(f"- `{n}.mdc` — {d}\n" for n, d in requested)
  )
  if dual_workspace() and MONITOR_RULES_SRC.is_dir():
    m_always, m_requested, m_stubs = scan(
      MONITOR_RULES_SRC, "MONITOR_ROUTER_ENTRIES", monitor=True
    )
    files.update(m_stubs)
    files[STUB_DIR / f"{MONITOR_STUB_PREFIX}always-on.md"] = (
      "---\npaths:\n" + f"  - {json.dumps('**/monitor/**')}\n" + "---\n"
      + HEADER
      + "\n# Monitor rules: always on for monitor work (dual workspace)\n\n"
      + f"Edits under `{MONITOR_SCOPE}` follow `HPCPerfStats/monitor/cursor-rules/`, not "
      + "`.cursor/rules/`. Before the first monitor edit of a turn, Read each of these in full "
      + "(the PreToolUse hook denies monitor edits until they were Read this turn):\n\n"
      + "".join(f"- `HPCPerfStats/monitor/cursor-rules/{n}.mdc`\n" for n in m_always)
    )
    if m_requested:
      requested_md += (
        "\n## Monitor rules (dual workspace; `HPCPerfStats/monitor/**` work only)\n\n"
        + "Files live in `HPCPerfStats/monitor/cursor-rules/`.\n\n"
        + "".join(f"- `{n}.mdc` — {d}\n" for n, d in m_requested)
      )
  files[CLAUDE / "cursor-agent-requested.md"] = requested_md
  return files


def main() -> int:
  files = build()
  changed = []
  for path, content in files.items():
    if not path.exists() or path.read_text(encoding="utf-8") != content:
      changed.append(path)
  stale = [
    p for p in STUB_DIR.glob(f"{STUB_PREFIX}*.md")
    if p not in files
  ] if STUB_DIR.is_dir() else []
  if "--check" in sys.argv:
    for p in changed + stale:
      print(f"would update: {p.relative_to(ROOT)}")
    return 1 if (changed or stale) else 0
  STUB_DIR.mkdir(parents=True, exist_ok=True)
  for path in changed:
    path.write_text(files[path], encoding="utf-8")
  for p in stale:
    p.unlink()
  print(f"cursor rules synced: {len(files)} files, {len(changed)} written, {len(stale)} removed")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
